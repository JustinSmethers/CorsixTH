test("phase 7 audio flow: gesture-safe init and no Chromium autoplay policy violations", async ({ page }) => {
    const autoplayViolations = [];
    page.on("console", (message) => {
        const text = message.text();
        if (/AudioContext was not allowed to start/i.test(text) || /autoplay/i.test(text)) {
            autoplayViolations.push(text);
        }
    });
    await importAssetsAndEnterPlayableShell(page);
    await expect(page.getByTestId("audio-status")).toHaveText("Audio: waiting-for-user-gesture");
    await page.getByTestId("admit").click();
    await expect(page.getByTestId("audio-status")).toHaveText("Audio: running");
    await expect(page.getByTestId("audio-volume-metric")).toHaveText("Audio volume: 100% (sound on, music on)");
    await page.getByTestId("playfield").focus();
    await page.keyboard.press("Alt+KeyS");
    await expect(page.getByTestId("audio-volume-metric")).toHaveText("Audio volume: 100% (sound off, music on)");
    await page.keyboard.press("Alt+KeyM");
    await expect(page.getByTestId("audio-volume-metric")).toHaveText("Audio volume: 100% (sound off, music off)");
    await page.keyboard.press("Alt+KeyS");
    await expect(page.getByTestId("audio-volume-metric")).toHaveText("Audio volume: 100% (sound on, music off)");
    await page.keyboard.press("Alt+KeyM");
    await expect(page.getByTestId("audio-volume-metric")).toHaveText("Audio volume: 100% (sound on, music on)");
    await page.getByTestId("playfield").focus();
    const audioVolumeBeforeJukebox = (await page.getByTestId("audio-volume-metric").textContent()) ?? "";
    await page.keyboard.press("KeyJ");
    await expect(page.locator(":focus")).toHaveAttribute("data-testid", "audio-volume");
    await expect(page.getByTestId("audio-volume-metric")).toHaveText(audioVolumeBeforeJukebox);
    await expect(page.getByTestId("action-status")).toHaveText("Action: jukebox opened");
    await expect.poll(() => autoplayViolations).toEqual([]);
});
