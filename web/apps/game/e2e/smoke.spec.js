function parseMetric(raw, label) {
    const match = raw.match(new RegExp(`^${label}:\\s*(-?\\d+)$`));
    if (!match) {
        throw new Error(`Unable to parse ${label} metric from: ${raw}`);
    }
    return Number(match[1]);
}
